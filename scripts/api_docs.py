def _attribute_docs(path: str) -> Dict[str, str]:
    """Strings that follow an assignment at module level (attribute docstrings): name -> text, cleaned."""
    with open(path, encoding="utf-8") as f:
        tree = ast.parse(f.read())
    found: Dict[str, str] = {}
    body = tree.body
    for node, after in zip(body, body[1:], strict=False):
        if (
            isinstance(node, ast.Assign)
            and isinstance(after, ast.Expr)
            and isinstance(after.value, ast.Constant)
            and isinstance(after.value.value, str)
        ):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    found[target.id] = inspect.cleandoc(after.value.value)
    return found


def _doc_of(name: str, obj, attributes: Dict[str, str]) -> str:
    if name in attributes:
        return attributes[name]
    doc = inspect.getdoc(obj)
    if not doc:
        raise SystemExit(f"api_docs: {name} has no docstring")
    return doc


def parse_doc(doc: str) -> dict:
    """Split a Google-style docstring into its summary, body and sections."""
    head: List[str] = []
    sections: Dict[str, List[str]] = {}
    current: Optional[str] = None
    for line in inspect.cleandoc(doc).split("\n"):
        mark = SECTION_RE.match(line)
        if mark:
            current = mark.group(1)
            sections[current] = []
        elif current:
            sections[current].append(line)
        else:
            head.append(line)
    paragraphs = "\n".join(head).strip().split("\n\n", 1)
    summary = " ".join(paragraphs[0].split())
    body = paragraphs[1].strip() if len(paragraphs) > 1 else ""
    return {
        "summary": summary,
        "body": body,
        "sections": {k: textwrap.dedent("\n".join(v)).strip("\n") for k, v in sections.items()},
    }


def parse_entries(text: str, pattern: str) -> List[Tuple[str, str]]:
    """Entries `name: text` at the left edge with continuation lines indented; pattern captures the name(s)."""
    entries: List[Tuple[str, List[str]]] = []
    for line in text.split("\n"):
        start = re.match(rf"^({pattern}):(?:\s+(.*))?$", line)
        if start and not line.startswith(" "):
            entries.append((start.group(1), [start.group(2) or ""]))
        elif entries and line.strip():
            entries[-1][1].append(line.strip())
        elif entries and not line.strip():
            entries[-1][1].append("")
    return [(name, " ".join(" ".join(parts).split())) for name, parts in entries]


NAME = r"\*{0,2}[A-Za-z_][A-Za-z0-9_]*"
CLASSES = r"[A-Za-z_][\w.]*(?:, [A-Za-z_][\w.]*)*"


def clean_type(text: str) -> str:
    text = text.replace('"', "").replace("'", "")
    for alias, real in TYPE_ALIASES.items():
        text = re.sub(rf"\b{alias}\b", real, text)
    return text


def signature_parts(obj, skip_self: bool = True) -> Tuple[List[dict], str]:
    """The parameters (name, type, default, kind) and the return annotation of a callable."""
    sig = inspect.signature(obj)
    params = []
    for p in sig.parameters.values():
        if p.name == "self" and skip_self:
            continue
        params.append(
            {
                "name": p.name,
                "kind": p.kind,
                "type": "" if p.annotation is p.empty else clean_type(str(p.annotation)),
                "default": None if p.default is p.empty else repr(p.default),
            }
        )
    returns = "" if sig.return_annotation in (sig.empty, "None") else clean_type(str(sig.return_annotation))
    return params, returns


def signature_text(name: str, obj, kind: str) -> str:
    params, returns = signature_parts(obj)
    parts: List[str] = []
    star = False
    for p in params:
        if p["kind"] is inspect.Parameter.KEYWORD_ONLY and not star:
            parts.append("*")
            star = True
        label = {inspect.Parameter.VAR_POSITIONAL: "*", inspect.Parameter.VAR_KEYWORD: "**"}.get(p["kind"], "") + p[
            "name"
        ]
        text = label + (f": {p['type']}" if p["type"] else "")
        if p["default"] is not None:
            text += f" = {p['default']}"
        parts.append(text)
    tail = f" -> {returns}" if returns and kind != "class" else ""
    one = f"{name}({', '.join(parts)}){tail}"
    if len(one) <= 100 or not parts:
        return one
    return f"{name}(\n" + "".join(f"    {part},\n" for part in parts) + f"){tail}"


# Rendering


class Index:
    """Where each name of the API lives: name -> (page file, anchor)."""

    def __init__(self) -> None:
        self.where: Dict[str, Tuple[str, str]] = {}
        self.members: Dict[str, List[str]] = {}

    def add(self, name: str, page: str, anchor: str) -> None:
        self.where[name] = (page, anchor)

    def link(self, name: str, from_page: str) -> Optional[str]:
        if name not in self.where:
            return None
        page, anchor = self.where[name]
        return f"#{anchor}" if page == from_page else f"{page}#{anchor}"


def anchor_of(name: str) -> str:
    """The id of an entry. Double underscores are dropped: in a heading they would be read as emphasis inside {#id}."""
    return re.sub(r"[^a-z0-9_-]+", "-", name.lower().replace("__", "").replace(".", "-")).strip("-")


def link_prose(text: str, page: str, index: Index, context: Optional[str], self_name: Optional[str]) -> str:
    """Turn a code span that names an API entry into a link to it; leave everything else as it is."""

    def replace(match: "re.Match[str]") -> str:
        token = match.group(1)
        key = token[:-2] if token.endswith("()") else token
        for candidate in (key, f"{context}.{key}" if context else None):
            if candidate and candidate in index.where and candidate != self_name:
                if self_name in index.where and index.where[candidate] == index.where[self_name]:
                    return match.group(0)  # it would point at the entry being read
                return f"[`{token}`]({index.link(candidate, page)})"
        return match.group(0)

    # Code spans only, outside fenced blocks (prose passed here never holds a fence).
    return re.sub(r"(?<!\[)`([^`\n]+)`(?!\])", replace, text)


def cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def type_cell(text: str, page: str, index: Index) -> str:
    """A type as code, with each public name in it as a link."""
    if not text:
        return ""
    pieces = re.split(r"(\b[A-Za-z_]\w*\b)", text)
    out = []
    for piece in pieces:
        if not piece:
            continue
        if piece in index.where and piece[0].isupper():
            out.append(f"[`{piece}`]({index.link(piece, page)})")
        else:
            out.append(f"`{piece}`" if piece.strip() else piece)
    return cell("".join(out).replace("``", ""))


def render_example(block: str) -> List[str]:
    lines = textwrap.dedent(block).strip("\n").split("\n")
    marker = MARKER_RE.match(lines[0]) if lines else None
    out: List[str] = []
    if marker:
        out += [f"<!-- {marker.group(1)} -->", ""]
        lines = lines[1:]
    return out + ["```python", *lines, "```", ""]


def sections_markdown(
    doc: dict, page: str, index: Index, context: Optional[str], self_name: Optional[str], skip: Tuple[str, ...] = ()
) -> List[str]:
    """Returns, Raises, Note, Example and See also of one docstring, in that order (less the sections in `skip`)."""
    link = lambda t: link_prose(t, page, index, context, self_name)  # noqa: E731
    s = doc["sections"]
    out: List[str] = []
    if "Returns" in s and "Returns" not in skip:
        out += ["**Returns:** " + link(" ".join(s["Returns"].split())), ""]
    if "Raises" in s:
        rows = ["**Raises**", ""]
        for names, text in parse_entries(s["Raises"], CLASSES):
            lead = re.match(r"^`(error\.[a-z_.]+)`: (.*)$", text)  # a docstring entry may start with its code
            if lead:
                text = lead.group(2)[:1].upper() + lead.group(2)[1:]
            codes = [lead.group(1)] if lead else sorted(set(re.findall(r"`(error\.[a-z_.]+)`", text)))
            api = _api()
            listed = names.split(", ")
            others = False
            if not codes:
                for name in listed:  # every class of a grouped row shows its own code, never the first one's
                    cls = getattr(api, name, None)
                    if cls is not None and hasattr(cls, "default_code") and name != "AnonymizerError":
                        if cls.default_code not in codes:
                            codes.append(cls.default_code)
                    elif name == "AnonymizerError" and len(listed) > 1:
                        others = True
            shown_codes = ", ".join(f"`{c}`" for c in codes)
            if others:
                shown_codes += ", others"
            if not shown_codes and not hasattr(api, listed[0]):
                shown_codes = "builtin"
            who = ", ".join(
                (f"[`{n}`]({index.link(n, page)})" if n in index.where else f"`{n}`") for n in names.split(", ")
            )
            # a code the text already names is not repeated in front of it
            named = re.findall(r"`(error\.[a-z_.]+)`", text)
            if named and not others and shown_codes != "builtin":
                shown_codes = ""
            rows.append(f"- {who}" + (f" ({shown_codes})" if shown_codes else "") + f": {cell(link(text))}")
        out += rows + [""]
    if "Note" in s:
        out += ["!!! note", ""] + [("    " + ln if ln.strip() else "") for ln in link(s["Note"]).split("\n")] + [""]
    if "Example" in s:
        blocks = re.findall(r"```python\n(.*?)```", s["Example"], re.S)
        if blocks:
            out += ["**Example**", ""]
            for block in blocks:
                out += render_example(block)
    if "See also" in s and "See also" not in skip:
        names = re.findall(r"`([^`]+)`", s["See also"])
        parts = [f"[`{n}`]({index.link(n, page)})" if n in index.where else f"`{n}`" for n in names]
        out += ["**See also:** " + ", ".join(parts), ""]
    return out


def params_list(
    entries: List[Tuple[str, str]], params: List[dict], page: str, index: Index, context, self_name, title: str
) -> List[str]:
    by_name = {name.lstrip("*"): text for name, text in entries}
    names = [p["name"] for p in params]
    unknown = [n for n in by_name if n not in names]
    missing = [n for n in names if n not in by_name]
    if unknown or missing:
        raise SystemExit(
            f"api_docs: {self_name}: Args names {unknown} not in the signature / signature names {missing} not in Args"
        )
    rows = []
    for p in params:
        default = "required" if p["default"] is None else f"default `{p['default']}`"
        label = {inspect.Parameter.VAR_POSITIONAL: "*", inspect.Parameter.VAR_KEYWORD: "**"}.get(p["kind"], "") + p[
            "name"
        ]
        if p["kind"] is inspect.Parameter.VAR_POSITIONAL:
            default = ""
        facts = ", ".join(x for x in (type_cell(p["type"], page, index), default) if x)
        rows.append(
            f"- `{label}`" + (f" ({facts})" if facts else "") + ": "
            f"{cell(link_prose(by_name[p['name']], page, index, context, self_name))}"
        )
    return rows + [""]


def attributes_list(
    cls, entries: List[Tuple[str, str]], page: str, index: Index, context: str, self_name: str
) -> List[str]:
    """The attributes of a class: with types and defaults for a dataclass, text only otherwise."""
    fields = {f.name: f for f in dataclasses.fields(cls)} if dataclasses.is_dataclass(cls) else {}
    typed = bool(fields)
    rows: List[str] = []
    documented = [name for name, _ in entries]
    for name in fields:
        if name not in documented:
            raise SystemExit(f"api_docs: {self_name}: field {name} has no line under Attributes")
    if typed:  # the fields in constructor order, then any class attribute the docstring describes
        described = dict(entries)
        entries = [(n, described[n]) for n in fields] + [(n, x) for n, x in entries if n not in fields]
    for name, text in entries:
        body = cell(link_prose(text, page, index, context, self_name))
        if not typed:
            rows.append(f"- `{name}`: {body}")
            continue
        if name in fields:
            f = fields[name]
            if f.default is not dataclasses.MISSING:
                default = f"`{f.default!r}`"
            elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
                default = f"`{f.default_factory()!r}`"  # type: ignore[misc]
            else:
                default = "required"
            default = default if default == "required" else f"default {default}"
            rows.append(f"- `{name}` ({type_cell(clean_type(str(f.type)), page, index)}, {default}): {body}")
        else:  # a class attribute such as `type` or `default_code`
            value = getattr(cls, name)
            rows.append(f"- `{name}` (`{type(value).__name__}`, class attribute, `{value!r}`): {body}")
    return rows + [""]


def label_of(name: str, obj) -> str:
    _api()
    if isinstance(obj, type) and issubclass(obj, Exception):
        base = obj.__mro__[1]
        return (
            "Exception."
            if base is Exception
            else f"Exception, a subclass of [`{base.__name__}`](errors.md#{anchor_of(base.__name__)})."
        )
    if dataclasses.is_dataclass(obj):
        frozen = obj.__dataclass_params__.frozen  # type: ignore[attr-defined]
        return "Frozen dataclass." if frozen else "Dataclass."
    if isinstance(obj, type):
        return "Class."
    if inspect.isfunction(obj):
        return "Function."
    return ""


def render_class(name: str, page: str, index: Index, attributes: Dict[str, str]) -> List[str]:
    api = _api()
    cls = getattr(api, name)
    doc = parse_doc(_doc_of(name, cls, attributes))
    link = lambda t: link_prose(t, page, index, name, name)  # noqa: E731
    out = [f"## {name} {{ #{anchor_of(name)} }}", ""]
    if name not in NO_SIGNATURE and not dataclasses.is_dataclass(cls):
        out += ["```text", signature_text(name, cls, "class"), "```", ""]
    label = label_of(name, cls) if dataclasses.is_dataclass(cls) or issubclass(cls, Exception) else ""
    out += [(label + " " if label else "") + link(doc["summary"]), ""]
    if doc["body"]:
        out += [link(doc["body"]), ""]
    s = doc["sections"]
    if "Args" in s:
        params, _ = signature_parts(cls)
        out += ["**Parameters**", ""]
        out += params_list(parse_entries(s["Args"], NAME), params, page, index, name, name, "Parameter")
    if "Attributes" in s and name not in HEADED_FIELDS:
        out += ["**Attributes**", ""]
        out += attributes_list(cls, parse_entries(s["Attributes"], NAME), page, index, name, name)
    if name in HEADED_FIELDS:
        entries = parse_entries(s["Attributes"], NAME)
        fields = {f.name: f for f in dataclasses.fields(cls)}
        for field_name, text in entries:
            f = fields[field_name]
            if f.default is not dataclasses.MISSING:
                default = repr(f.default)
            else:
                default = "required"
            out += [
                f"### `{name}.{field_name}` {{ #{anchor_of(name + '.' + field_name)} }}",
                "",
                f"Type {type_cell(clean_type(str(f.type)), page, index)}, default `{default}`.",
                "",
                link_prose(text, page, index, name, f"{name}.{field_name}"),
                "",
            ]
    out += sections_markdown(doc, page, index, name, name, skip=())
    out += render_members(name, cls, page, index)
    return out


def class_members(cls) -> List[Tuple[str, object]]:
    """Public methods and properties defined on the class itself, in definition order. The context-manager methods are left
    out: the class says that it is used in a `with` block."""
    members = []
    for member_name, member in vars(cls).items():
        if member_name.startswith("_"):
            continue
        if isinstance(member, property) or inspect.isfunction(member):
            members.append((member_name, member))
    return members


def render_members(name: str, cls, page: str, index: Index) -> List[str]:
    out: List[str] = []
    for member_name, member in class_members(cls):
        qualified = f"{name}.{member_name}"
        fn = member.fget if isinstance(member, property) else member
        doc = parse_doc(inspect.getdoc(fn) or "")
        out += [f"### `{qualified}` {{ #{anchor_of(qualified)} }}", ""]
        if isinstance(member, property):
            _, returns = signature_parts(fn)
            out += ["Property" + (f" of type {type_cell(returns, page, index)}." if returns else "."), ""]
        else:
            out += ["```text", signature_text(member_name, fn, "method"), "```", ""]
        out += [link_prose(doc["summary"], page, index, name, qualified), ""]
        if doc["body"]:
            out += [link_prose(doc["body"], page, index, name, qualified), ""]
        s = doc["sections"]
        if "Args" in s:
            params, _ = signature_parts(fn)
            out += ["**Parameters**", ""]
            out += params_list(parse_entries(s["Args"], NAME), params, page, index, name, qualified, "Parameter")
        skip = ("See also", "Returns") if isinstance(member, property) else ("See also",)
        out += sections_markdown(doc, page, index, name, qualified, skip=skip)
    return out


def render_function(name: str, page: str, index: Index, attributes: Dict[str, str]) -> List[str]:
    api = _api()
    fn = getattr(api, name)
    doc = parse_doc(_doc_of(name, fn, attributes))
    link = lambda t: link_prose(t, page, index, None, name)  # noqa: E731
    out = [f"## {name} {{ #{anchor_of(name)} }}", ""]
    out += ["```text", signature_text(name, fn, "function"), "```", "", link(doc["summary"]), ""]
    if doc["body"]:
        out += [link(doc["body"]), ""]
    s = doc["sections"]
    if "Args" in s:
        params, _ = signature_parts(fn)
        out += ["**Parameters**", ""]
        out += params_list(parse_entries(s["Args"], NAME), params, page, index, None, name, "Parameter")
    out += sections_markdown(doc, page, index, None, name)
    return out


def render_constant(name: str, page: str, index: Index, attributes: Dict[str, str]) -> List[str]:
    value = getattr(_api(), name)
    doc = parse_doc(attributes[name])
    items = [repr(v) for v in value]
    lines = textwrap.wrap(", ".join(items) + ",", width=96)
    out = [f"## {name} {{ #{anchor_of(name)} }}", "", "Constant, a tuple of strings.", ""]
    out += ["```text", f"{name} = (", *[f"    {ln}" for ln in lines], ")", "```", ""]
    out += [link_prose(doc["summary"], page, index, None, name), ""]
    if doc["body"]:
        out += [link_prose(doc["body"], page, index, None, name), ""]
    return out


def render_event_alias(page: str, index: Index, attributes: Dict[str, str]) -> List[str]:
    _api()
    doc = parse_doc(attributes["Event"])
    members = [n for n in ("Started", "Progress", "ItemFound", "Analyzed", "Rendered", "JobWarning", "Finished")]
    out = ["## Event { #event }", "", "Type alias.", ""]
    out += ["```text", "Event = Union[" + ", ".join(members) + "]", "```", ""]
    out += [link_prose(doc["summary"], page, index, None, "Event"), ""]
    if doc["body"]:
        out += [link_prose(doc["body"], page, index, None, "Event"), ""]
    return out


def render_page(spec: dict, index: Index, attributes: Dict[str, str]) -> str:
    page = spec["file"]
    api = _api()
    lines = [GENERATED_NOTE, "", f"# {spec['title']}", "", link_prose(spec["intro"], page, index, None, None), ""]
    for name in spec["entries"]:
        obj = getattr(api, name)
        if name == "Event":
            lines += render_event_alias(page, index, attributes)
        elif name in ("PHOTO_EXTENSIONS", "VIDEO_EXTENSIONS", "UNSUPPORTED_EXTENSIONS"):
            lines += render_constant(name, page, index, attributes)
        elif isinstance(obj, type):
            lines += render_class(name, page, index, attributes)
        else:
            lines += render_function(name, page, index, attributes)
    if spec["file"] == "errors.md":
        lines += codes_sections()
    lines += [""]
    text = "\n".join(lines)
    return re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"


