def build_index(attributes: Dict[str, str]) -> Index:
    api = _api()
    index = Index()
    for spec in PAGES:
        for name in spec["entries"]:
            index.add(name, spec["file"], anchor_of(name))
            obj = getattr(api, name)
            if isinstance(obj, type):
                if name in HEADED_FIELDS:
                    for f in dataclasses.fields(obj):
                        index.add(f"{name}.{f.name}", spec["file"], anchor_of(f"{name}.{f.name}"))
                else:
                    if dataclasses.is_dataclass(obj):
                        for f in dataclasses.fields(obj):
                            index.add(f"{name}.{f.name}", spec["file"], anchor_of(name))
                for member_name, _ in class_members(obj):
                    index.add(f"{name}.{member_name}", spec["file"], anchor_of(f"{name}.{member_name}"))
                if not dataclasses.is_dataclass(obj):
                    attrs = parse_doc(_doc_of(name, obj, attributes))["sections"].get("Attributes", "")
                    for attr, _ in parse_entries(attrs, NAME):
                        index.where.setdefault(f"{name}.{attr}", (spec["file"], anchor_of(name)))
    index.add("Reasons and codes", "errors.md", "reasons")
    return index


def pages() -> Dict[str, str]:
    """File name -> text of every generated page of docs/reference/."""
    api = _api()
    attributes: Dict[str, str] = {}
    attributes.update(_attribute_docs(os.path.join(ROOT, "src", "anonymizer", "api.py")))
    attributes.update(_attribute_docs(os.path.join(ROOT, "src", "anonymizer", "engine", "files.py")))
    names = {n for spec in PAGES for n in spec["entries"]}
    unlisted = sorted(set(api.__all__) - names)
    if unlisted:
        raise SystemExit(f"api_docs: public names with no page: {unlisted}")
    index = build_index(attributes)
    return {spec["file"]: render_page(spec, index, attributes) for spec in PAGES}


# The old single page (docs/API.md), kept while tests/test_docs.py compares it


def _legacy_signature(name: str, obj) -> str:
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return name
    parts, keyword_only = [], False
    for p in sig.parameters.values():
        if p.name == "self":
            continue
        if p.kind is p.KEYWORD_ONLY and not keyword_only:
            parts.append("*")
            keyword_only = True
        text = p.name if p.annotation is p.empty else f"{p.name}: {p.annotation}"
        if p.default is not p.empty:
            text += f" = {p.default!r}"
        parts.append(text)
    returns = sig.return_annotation
    tail = "" if returns in (sig.empty, "None", None) else f" -> {returns}"
    return f"{name}({', '.join(parts)}){tail}"


def _legacy_members(cls) -> list:
    out = []
    for name, member in inspect.getmembers(cls):
        if name.startswith("_") or name in ("default_code", "type"):
            continue
        if name in getattr(cls, "__dataclass_fields__", {}):
            continue
        if isinstance(inspect.getattr_static(cls, name), property):
            out.append((name, f"{name} (property)", inspect.getdoc(member)))
        elif inspect.isfunction(member):
            out.append((name, _legacy_signature(name, member), inspect.getdoc(member)))
    return out


def render() -> str:
    """The old docs/API.md: a dump of the docstrings. Replaced by the pages of docs/reference/."""
    anonymizer = _api()
    sections = [
        ("Functions", lambda obj: inspect.isfunction(obj)),
        ("Errors", lambda obj: inspect.isclass(obj) and issubclass(obj, Exception)),
        ("Events", lambda obj: inspect.isclass(obj) and hasattr(obj, "type") and dataclasses.is_dataclass(obj)),
        ("Classes", lambda obj: inspect.isclass(obj)),
    ]
    lines = [
        "# API reference",
        "",
        "Generated from the docstrings by `scripts/api_docs.py`; edit the code, not this file. Everything listed here",
        "is exported by the `anonymizer` package; anything else in it is internal.",
        "",
    ]
    done = set()
    for title, belongs in sections:
        names = [n for n in sorted(anonymizer.__all__) if n not in done and belongs(getattr(anonymizer, n))]
        if not names:
            continue
        lines += [f"## {title}", ""]
        for name in names:
            done.add(name)
            obj = getattr(anonymizer, name)
            lines += [f"### `{_legacy_signature(name, obj)}`", ""]
            doc = inspect.getdoc(obj)
            if doc and not (dataclasses.is_dataclass(obj) and doc.startswith(f"{name}(")):
                lines += [doc, ""]
            if title == "Errors":
                lines += [f"Code: `{obj.default_code}`", ""]
            elif title == "Events":
                lines += [f"JSON type: `{obj.type}`", ""]
            else:
                for _, sig, mdoc in _legacy_members(obj) if inspect.isclass(obj) else []:
                    lines += [f"- `{sig}`" + (f": {mdoc}" if mdoc else ""), ""]
    rest = [n for n in sorted(anonymizer.__all__) if n not in done]
    if rest:
        lines += ["## Types", ""] + [f"- `{n}`" for n in rest] + [""]
    return "\n".join(lines).rstrip() + "\n"


def stale_pages() -> List[str]:
    """Names of the committed files that differ from what the code gives now."""
    stale = []
    for name, text in sorted(pages().items()):
        path = os.path.join(REFERENCE, name)
        try:
            with open(path, encoding="utf-8") as f:
                if f.read() != text:
                    stale.append(f"docs/reference/{name}")
        except OSError:
            stale.append(f"docs/reference/{name}")
    if os.path.exists(TARGET):
        with open(TARGET, encoding="utf-8") as f:
            if f.read() != render():
                stale.append("docs/API.md")
    return stale


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Write the API reference pages of docs/reference/ from the public docstrings."
    )
    parser.add_argument("--check", action="store_true", help="exit 1 if a committed page is out of date, and name it")
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_pages()
        if stale:
            print("out of date: " + ", ".join(stale) + "; run python3 scripts/api_docs.py", file=sys.stderr)
            return 1
        return 0
    os.makedirs(REFERENCE, exist_ok=True)
    for name, text in pages().items():
        with open(os.path.join(REFERENCE, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    if os.path.exists(TARGET):
        with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
            f.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main())
